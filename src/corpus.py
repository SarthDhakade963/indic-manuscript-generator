def _dev_num(n):
    return "".join(chr(0x0966 + int(d)) for d in str(n))


class _Pool:
    """Draws without replacement from a shuffled pool; reshuffles only when empty."""
    def __init__(self, items, rng):
        self.items, self.rng, self.q = list(items), rng, []

    def take(self):
        if not self.q:
            self.q = [self.items[i] for i in self.rng.permutation(len(self.items))]
        return self.q.pop()


def get_paragraphs(script, rng, n_blocks=3):
    """Returns (paragraphs in target script, devanagari source blocks)."""
    counter = [int(rng.integers(1, 300))]

    def num():
        n = counter[0]
        counter[0] += 1 + (1 if rng.random() < 0.08 else 0)
        return _dev_num(n)

    if script == "sharada":
        pool = _Pool(SANSKRIT_VERSES, rng)
        src = [" ".join(pool.take() + " ॥" + num() + "॥" for _ in range(int(rng.integers(1, 4))))
               for _ in range(n_blocks)]
    else:
        pool = _Pool(MARATHI_FRAGS, rng)

        def ovi():
            k = int(rng.integers(3, 6))
            return " । ".join(pool.take() for _ in range(k)) + " ।" + num() + "।"

        src = [" ".join(ovi() for _ in range(int(rng.integers(2, 5)))) for _ in range(n_blocks)]
    paras = [convert(p, script) for p in src]
    if rng.random() < 0.85:
        paras = [convert(str(rng.choice(HEADERS)), script)] + paras
    return paras, src